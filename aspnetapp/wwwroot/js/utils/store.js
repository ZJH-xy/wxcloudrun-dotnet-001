// 保存数据
async function saveClick(event) {
    loadHTML(); // 显示加载中

    console.log("开始调用接口...");


    const response = await fetch(`${RESPONSEURL}?handler=SayHello`, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'RequestVerificationToken': TOKEN // 添加 CSRF Token
        },
    });

    if (!response.ok) {
        throw new Error(`HTTP 错误！状态码: ${response.status}`);
    }

    const data = await response.json();  // 等待接口返回数据

    if (data.success) {
        console.log("接口返回数据:", data);
    } else {
        alert("文件上传失败: " + (data.message || "未知错误"));
    }

    try {
        // 创建 FormData 对象，准备上传文件
        const formData = new FormData();

        formData.append("key", data["filePath"]); // 上传的文件路径
        formData.append("Signature", data["authorization"]); // 上传的签名
        formData.append("x-cos-security-token", data["token"]); // 安全令牌
        formData.append("x-cos-meta-fileid", data["cos_file_id"]); // 文件 ID
        formData.append("file", file, file.name); // 文件内容

        const uploadResponse = await uploadFile(data["imageUrl"], formData);  // 异步上传文件
        console.log("Upload success:", uploadResponse);

        setTimeout(function () {
            cancelloadHTML();// 取消显示加载中
        }, 2500)

    } catch (error) {
        console.error("Error during upload:", error);
    }


}

// 加载文件
