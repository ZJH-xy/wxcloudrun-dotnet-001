// 处理删除按钮点击事件
async function confirmDelete(event) {

    // 弹出确认框
    const isConfirmed = confirm("确定要删除吗？");

    if (isConfirmed) {
        // 使用 event.target 获取被点击的按钮元素
        const button = event.target;
        // 获取 data-id 属性的值
        const deleteId = button.getAttribute('data-id');
        console.log('确认删除,ID:' + deleteId)
        loadHTML();
        const requestData = {
            id: deleteId
        };
        console.log("requestData...", requestData);

        try {
            const response = await fetch(`${RESPONSEURL}?handler=delete`, {
                method: 'Post',
                headers: {
                    'Content-Type': 'application/json',
                    'RequestVerificationToken': TOKEN // 添加 CSRF Token
                },
                body: JSON.stringify(requestData), // 将数据序列化为 JSON 格式
            });

            if (!response.ok) {
                throw new Error(`HTTP 错误！状态码: ${response.status}`);
            }

            const data = await response.json();  // 等待接口返回数据

            if (data.success) {
                console.log("删除成功，message:", data.message);
            } else {
                console.log("删除失败，message:", data.message);
            }

        } catch (error) {
            console.error("API 调用失败:", error);
        } finally {
            cancelloadHTML();
        }

    }
}





